// When this page was generated by `--html` (a shareable, self-contained
// export) rather than served live, the report data is embedded inline and
// there's no server to call — render it directly and hide the controls
// that would otherwise let you run a new analysis.
function renderEmbeddedReportIfPresent() {
  const embedded = window.__CSS_AUDIT_EMBEDDED_REPORT__;
  if (!embedded) return;

  document.querySelector(".url-row")?.setAttribute("hidden", "");
  document.querySelector(".tabs")?.setAttribute("hidden", "");

  if (embedded.kind === "css") {
    document.getElementById("tab-css").hidden = false;
    document.getElementById("tab-a11y").hidden = true;
    analyzeBtn.setAttribute("hidden", "");
    currentData = embedded.data;
    renderSummary(embedded.data);
    renderFilterBar(embedded.data);
    renderResults(embedded.data);
  } else {
    document.getElementById("tab-a11y").hidden = false;
    document.getElementById("tab-css").hidden = true;
    a11yReportBtn.setAttribute("hidden", "");
    currentA11yData = embedded.data;
    renderAxeReport(embedded.data);
  }
}

// Enter key in the shared URL input triggers whichever tab is active.
urlInput.addEventListener("keydown", (e) => {
  if (e.key !== "Enter") return;
  e.preventDefault();
  const activeTab = document.querySelector(".tab-btn--active").dataset.tab;
  if (activeTab === "css") analyzeBtn.click();
  else a11yReportBtn.click();
});

// --- Tabs ---

function initTabs() {
  document.querySelectorAll(".tab-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      document.querySelectorAll(".tab-btn").forEach((b) => {
        b.classList.toggle("tab-btn--active", b === btn);
        b.setAttribute("aria-selected", String(b === btn));
      });
      document.querySelectorAll(".tab-panel").forEach((panel) => {
        panel.hidden = panel.dataset.tabPanel !== btn.dataset.tab;
      });
    });
  });
}

