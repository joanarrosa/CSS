analyzeBtn.addEventListener("click", async () => {
  const url = urlInput.value.trim();
  if (!url) {
    showError("Enter a URL above first.");
    return;
  }

  rememberUrl(url);
  activeCategory = "all";
  activeType = "all";
  setLoading(true);
  summaryEl.innerHTML = "";
  filterBarEl.innerHTML = "";
  resultsEl.innerHTML = "";

  try {
    const res = await fetch("/api/analyze", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ url }),
    });
    const data = await res.json();
    if (!res.ok) {
      showError(data.error || "Something went wrong.");
      return;
    }
    currentData = data;
    renderSummary(data);
    renderFilterBar(data);
    renderResults(data);
  } catch (err) {
    showError("Network error: " + err.message);
  } finally {
    setLoading(false);
  }
});

function restoreLastUrl() {
  try {
    const last = localStorage.getItem(LAST_URL_KEY);
    if (last) urlInput.value = last;
  } catch {
    // localStorage unavailable (private mode, etc.) — not essential, skip silently
  }
}

function rememberUrl(url) {
  try {
    localStorage.setItem(LAST_URL_KEY, url);
  } catch {
    // ignore
  }
}

function setLoading(loading) {
  analyzeBtn.disabled = loading;
  analyzeBtn.textContent = loading ? "Analyzing…" : "Analyze CSS";
  if (loading) {
    statusEl.textContent =
      "Loading the page in a headless browser and analyzing its CSS — this can take several seconds…";
    statusEl.className = "status status--loading";
  }
}

function showError(msg) {
  statusEl.textContent = msg;
  statusEl.className = "status status--error";
}

