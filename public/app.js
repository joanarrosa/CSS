function downloadJson(data, prefix) {
  const blob = new Blob([JSON.stringify(data, null, 2)], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  const hostname = safeHostname(data.url);
  a.href = url;
  a.download = `${prefix}-${hostname}-${Date.now()}.json`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

async function downloadHtml(kind, data) {
  const btn = document.getElementById(kind === "css" ? "download-html-btn" : "download-a11y-html-btn");
  const originalText = btn.textContent;
  btn.disabled = true;
  btn.textContent = "Building…";
  try {
    const res = await fetch("/api/export-html", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ kind, data }),
    });
    if (!res.ok) {
      const err = await res.json().catch(() => ({}));
      throw new Error(err.error || "Could not build the HTML report.");
    }
    const blob = await res.blob();
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    const hostname = safeHostname(data.url);
    a.href = url;
    a.download = `${kind === "a11y" ? "accessibility" : "css-audit"}-${hostname}-${Date.now()}.html`;
    document.body.appendChild(a);
    a.click();
    a.remove();
    URL.revokeObjectURL(url);
  } catch (err) {
    alert(err.message);
  } finally {
    btn.disabled = false;
    btn.textContent = originalText;
  }
}

function safeHostname(url) {
  try {
    return new URL(url).hostname;
  } catch {
    return "report";
  }
}

// --- Shared filter-bar UI ---
// Builds a labeled, card-styled filter panel: one or more rows, each with a
// text label and a group of toggle chips (checkbox-like: one active value
// per row, "All ..." always resets it).

function buildFilterBar(container, rows) {
  container.innerHTML = "";
  const panel = document.createElement("div");
  panel.className = "filter-panel";

  const heading = document.createElement("div");
  heading.className = "filter-panel-heading";
  heading.textContent = "Filter results";
  panel.appendChild(heading);

  for (const row of rows) {
    const group = document.createElement("div");
    group.className = "filter-group";

    const label = document.createElement("span");
    label.className = "filter-label";
    label.textContent = row.label;
    group.appendChild(label);

    const chips = document.createElement("div");
    chips.className = "filter-chips";
    for (const opt of row.options) {
      const chip = document.createElement("button");
      chip.type = "button";
      chip.className = "filter-chip";
      chip.dataset.row = row.key;
      chip.dataset.value = opt.value;
      chip.textContent = `${opt.label} (${opt.count})`;
      if (row.active === opt.value) chip.classList.add("filter-chip--active");
      chip.addEventListener("click", () => row.onSelect(opt.value));
      chips.appendChild(chip);
    }
    group.appendChild(chips);
    panel.appendChild(group);
  }

  container.appendChild(panel);
}

// --- CSS Audit filters + results ---

function renderFilterBar(data) {
  buildFilterBar(filterBarEl, [
    {
      key: "category",
      label: "Category:",
      active: activeCategory,
      onSelect: (value) => {
        activeCategory = value;
        renderFilterBar(currentData);
        renderResults(currentData);
      },
      options: [
        { value: "all", label: "All categories", count: sumCounts(data.summary.counts) },
        ...CATEGORY_ORDER.filter((c) => (data.summary.counts[c] || 0) > 0).map((c) => ({
          value: c,
          label: CATEGORY_LABELS[c],
          count: data.summary.counts[c] || 0,
        })),
      ],
    },
    {
      key: "type",
      label: "Type:",
      active: activeType,
      onSelect: (value) => {
        activeType = value;
        renderFilterBar(currentData);
        renderResults(currentData);
      },
      options: [
        { value: "all", label: "All types", count: data.summary.total },
        { value: "error", label: "Errors", count: data.summary.byType.error || 0 },
        { value: "improvement", label: "Improvements", count: data.summary.byType.improvement || 0 },
      ],
    },
  ]);
}

function sumCounts(counts) {
  return Object.values(counts).reduce((a, b) => a + b, 0);
}

function renderResults(data) {
  resultsEl.innerHTML = "";

  const categoriesToShow = activeCategory === "all" ? CATEGORY_ORDER : [activeCategory];

  let shown = 0;
  for (const cat of categoriesToShow) {
    let items = data.findings[cat] || [];
    if (activeType !== "all") items = items.filter((f) => f.type === activeType);
    if (items.length === 0) continue;

    items = [...items].sort((a, b) => {
      if (a.type !== b.type) return a.type === "error" ? -1 : 1;
      return (SEVERITY_WEIGHT[b.severity] || 0) - (SEVERITY_WEIGHT[a.severity] || 0);
    });

    shown += items.length;

    const section = document.createElement("details");
    section.className = "category-section";
    section.open = true;

    const summary = document.createElement("summary");
    summary.textContent = `${CATEGORY_LABELS[cat]} (${items.length})`;
    section.appendChild(summary);

    const description = data.categories && data.categories[cat] ? data.categories[cat].description : "";
    if (description) {
      const desc = document.createElement("p");
      desc.className = "category-description";
      desc.textContent = description;
      section.appendChild(desc);
    }

    const list = document.createElement("div");
    list.className = "finding-list";
    for (const f of items) {
      list.appendChild(renderFindingCard(f));
    }
    section.appendChild(list);
    resultsEl.appendChild(section);
  }

  if (shown === 0) {
    const emptyBox = document.createElement("div");
    emptyBox.className = "summary-card";
    emptyBox.textContent =
      activeCategory === "all" && activeType === "all"
        ? "No issues found across any category."
        : "No findings match the current filters.";
    resultsEl.appendChild(emptyBox);
  }

  resultsEl.scrollIntoView({ behavior: "smooth", block: "nearest" });
}

function renderFindingCard(f) {
  const card = document.createElement("div");
  card.className = `finding finding--${f.severity}`;
  card.innerHTML = `
    <div class="finding-header">
      <span class="sev-badge sev-badge--${f.severity}">${f.severity}</span>
      <span class="type-badge type-badge--${f.type}">${f.type}</span>
      ${f.selector ? `<code>${escapeHtml(f.selector)}</code>` : `<span class="doc-level">document-level</span>`}
    </div>
    ${f.source ? `<p class="where"><strong>Where:</strong> ${escapeHtml(f.source)}${f.line ? ":" + f.line : ""}</p>` : ""}
    <p class="problem"><strong>Problem:</strong> ${escapeHtml(f.message)}</p>
    ${f.suggestion ? `<p class="fix"><strong>Fix:</strong> ${escapeHtml(f.suggestion)}</p>` : ""}
  `;
  return card;
}

function escapeHtml(str) {
  return String(str).replace(
    /[&<>"']/g,
    (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c])
  );
}

function scoreBadgeHtml(summary) {
  if (summary.score === undefined) return "";
  return `
    <div class="score-badge score-badge--${summary.grade}" title="Overall score: ${summary.score}/100">
      <span class="score-badge-number">${summary.score}</span>
      <span class="score-badge-grade">${summary.grade}</span>
    </div>
  `;
}

